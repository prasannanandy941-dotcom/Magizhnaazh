/**
 * Resolve an arbitrary place name (e.g. from a geocoder) to a known city in our
 * catalogue, or null if it can't be matched. Tries exact match, then aliases,
 * then a loose contains match.
 */
export function findKnownCity(name: string | undefined | null): string | null {
  if (!name) return null;
  const norm = name.trim().toLowerCase();
  if (!norm) return null;
  if (CITY_LOOKUP[norm]) return CITY_LOOKUP[norm];
  if (CITY_ALIASES[norm]) return CITY_ALIASES[norm];
  for (const city of ALL_INDIA_CITIES) {
    const cl = city.toLowerCase();
    if (norm.includes(cl) || cl.includes(norm)) return city;
  }
  return null;
}

/**
 * Detect the visitor's city from their browser location. Requests geolocation
 * permission, reverse-geocodes the coordinates with a keyless public service,
 * and maps the result onto a known city. Resolves to null (never throws) when
 * geolocation is unavailable, permission is denied, the lookup fails, or the
 * detected place isn't in our catalogue — callers should keep their default.
 */
export async function detectUserCity(): Promise<string | null> {
  if (typeof navigator === "undefined" || !navigator.geolocation) return null;

  const coords = await new Promise<{ latitude: number; longitude: number } | null>(
    (resolve) => {
      navigator.geolocation.getCurrentPosition(
        (pos) => resolve({ latitude: pos.coords.latitude, longitude: pos.coords.longitude }),
        () => resolve(null),
        { timeout: 8000, maximumAge: 10 * 60 * 1000 }
      );
    }
  );
  if (!coords) return null;

  try {
    const res = await fetch(
      `https://api.bigdatacloud.net/data/reverse-geocode-client?latitude=${coords.latitude}&longitude=${coords.longitude}&localityLanguage=en`
    );
    if (!res.ok) return null;
    const data: {
      city?: string;
      locality?: string;
      principalSubdivision?: string;
    } = await res.json();
    for (const candidate of [data.city, data.locality, data.principalSubdivision]) {
      const match = findKnownCity(candidate);
      if (match) return match;
    }
    return null;
  } catch {
    return null;
  }
}
