/**
 * States/UTs in display order. South-Indian states surface first (the platform
 * is South-India focused), then every other state/UT alphabetically. Used to
 * render grouped <optgroup> location dropdowns.
 */
const PRIORITY_STATES = [
  "Tamil Nadu", "Andhra Pradesh", "Telangana", "Karnataka", "Kerala", "Puducherry",
];

export const ORDERED_STATES: string[] = [
  ...PRIORITY_STATES.filter((s) => s in INDIA_STATES_AND_CITIES),
  ...Object.keys(INDIA_STATES_AND_CITIES)
    .filter((s) => !PRIORITY_STATES.includes(s))
    .sort((a, b) => a.localeCompare(b)),
];

/** Unique, alphabetically-sorted list of cities for a single state/UT. */
export function citiesForState(state: string): string[] {
  return Array.from(new Set(INDIA_STATES_AND_CITIES[state] ?? [])).sort((a, b) =>
    a.localeCompare(b)
  );
}

/**
 * Group an arbitrary {name, state} city list (e.g. the backend's serviceable
 * cities from GET /api/v1/locations) into ordered [state, cities][] tuples for
 * rendering grouped <optgroup> dropdowns. States follow ORDERED_STATES first
 * (South-India priority), then any remaining states alphabetically; cities
 * within each state are de-duplicated and alphabetised.
 */
export function groupCitiesByState(
  cities: { name: string; state?: string }[]
): [string, string[]][] {
  const byState = new Map<string, Set<string>>();
  for (const { name, state } of cities) {
    if (!name) continue;
    const key = state?.trim() || "Other";
    if (!byState.has(key)) byState.set(key, new Set());
    byState.get(key)!.add(name.trim());
  }

  const orderedKeys = [
    ...ORDERED_STATES.filter((s) => byState.has(s)),
    ...Array.from(byState.keys())
      .filter((s) => !ORDERED_STATES.includes(s))
      .sort((a, b) => a.localeCompare(b)),
  ];

  return orderedKeys.map((state) => [
    state,
    Array.from(byState.get(state)!).sort((a, b) => a.localeCompare(b)),
  ]);
}

/** The full static catalogue pre-grouped — the offline fallback for dropdowns. */
export const STATIC_CITY_GROUPS: [string, string[]][] = ORDERED_STATES.map(
  (state) => [state, citiesForState(state)]
);

/** Flat, de-duplicated, alphabetically-sorted list of every city across India. */
export const ALL_INDIA_CITIES: string[] = Array.from(
  new Set(Object.values(INDIA_STATES_AND_CITIES).flat())
).sort((a, b) => a.localeCompare(b));

/** Reverse index: lowercased city name -> canonical city (first state wins). */
const CITY_LOOKUP: Record<string, string> = (() => {
  const map: Record<string, string> = {};
  for (const city of ALL_INDIA_CITIES) {
    map[city.toLowerCase()] = city;
  }
  return map;
})();

